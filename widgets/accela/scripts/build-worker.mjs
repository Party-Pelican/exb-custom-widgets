import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { stripTypeScriptTypes } from 'node:module'
const runtime = new URL('../widget/src/runtime/', import.meta.url)
const core = await readFile(new URL('accela-core.js', runtime), 'utf8')
const csv = stripTypeScriptTypes(await readFile(new URL('csv.ts', runtime), 'utf8'))
const engine = await readFile(new URL('worker-engine.js', runtime), 'utf8')
const bundle = '// Generated by npm run build:worker. Edit the source modules, then regenerate.\n' +
  [core, csv, engine].map(s => s.replace(/^export /gm, '')).join('\n') +
  '\nconst handle = createWorkerHandler({ createClient, validateSearch, searchParcels, toCsv, post: message => self.postMessage(message) });\nself.onmessage = event => { void handle(event.data) };\n'
await mkdir(new URL('assets/', runtime), {recursive:true})
await writeFile(new URL('assets/worker.js', runtime), bundle)
console.log('Generated widget/src/runtime/assets/worker.js')
